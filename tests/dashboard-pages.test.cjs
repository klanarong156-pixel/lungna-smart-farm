const assert = require('node:assert/strict');
const fs = require('node:fs');
const html = fs.readFileSync('dashboard/index.html', 'utf8');
const css = fs.readFileSync('dashboard/css/app.css', 'utf8');
const pageIds = [...html.matchAll(/data-page="([^"]+)"/g)].map(m => m[1]);
const navTargets = [...html.matchAll(/data-nav="([^"]+)"/g)].map(m => m[1]);
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(m => m[1]);
assert.deepEqual(pageIds, ['home','water','devices','connection-page','weather','settings','events']);
assert.ok(navTargets.every(target => pageIds.includes(target)), 'every nav target has a page');
assert.equal(new Set(ids).size, ids.length, 'DOM IDs must be unique');
assert.match(html, /<header class="topbar">[\s\S]*?id="connection"[\s\S]*?id="headerEsp"/);
assert.match(html, /<footer class="site-footer">/);
assert.match(html, /class="sidebar"[\s\S]*data-nav="events"/);
assert.match(html, /class="bottom-nav"[\s\S]*data-nav="events"/);
for (const token of ['--primary:','--primary-dark:','--primary-light:','--background:','--surface:','--surface-soft:','--text:','--text-muted:','--border:','--success:','--warning:','--danger:','--info:']) assert.ok(css.includes(token), `missing design token ${token}`);
assert.match(html, /DHT11/);
assert.match(html, /Soil Sensor/);
assert.match(html, /lungna-shell-v7/);
assert.match(html, /logo-suanlungna-modern\.png/);
assert.match(html, /class="farm-map-card"[\s\S]*data-farm-zone="pump"[\s\S]*data-farm-zone="zone1"[\s\S]*data-farm-zone="lighthome"[\s\S]*data-farm-zone="lightsala"/);
assert.match(html, /ผัง schematic สำหรับเลือกรีเลย์/);
const homeStart = html.indexOf('data-page="home"');
const waterStart = html.indexOf('data-page="water"');
const homeMarkup = html.slice(homeStart, waterStart);
assert.doesNotMatch(homeMarkup, /data-relay-toggle|data-mode|scheduleForm/, 'Home must route to controls without issuing commands');
assert.match(html, /id="temperature"[\s\S]*id="humidity"[\s\S]*id="homeEsp"[\s\S]*id="homeRelaySummary"/);
assert.match(html, /class="water-workspace"[\s\S]*id="waterRelays"/);
assert.match(html, /class="weather-layout"/);
assert.match(html, /class="settings-layout"/);
assert.match(html, /class="connection-hero"[\s\S]*id="mqttAutoStatus"/);
assert.match(html, /บันทึกและเชื่อมต่อครั้งแรก/);
for (const duplicateId of ['homeRelays','homeTempAgain','homeHumidityAgain','homeHeartbeat','homeMqttStatus','weatherSensorTemp','weatherSensorHumidity','deviceRelays','refreshBtn']) {
  assert.doesNotMatch(html, new RegExp(`id="${duplicateId}"`), `duplicate surface ${duplicateId} should be removed`);
}
assert.match(css, /--background:#0B1220/);
assert.match(css, /--surface:#111C30/);
assert.match(css, /--surface-soft:#18263B/);
assert.match(css, /--primary:#39F5A5/);
assert.match(css, /prefers-reduced-motion:reduce/);
const app = fs.readFileSync('dashboard/js/app.js', 'utf8');
assert.match(app, /page === 'finance'[\s\S]*?financeDisclosure\.open = true/);
assert.match(app, /function openFarmZone\(relayId\)[\s\S]*?scheduleRelay'\)\.value = relayId[\s\S]*?navigate\('water'\)/);
assert.match(app, /event\.key !== 'Enter'[\s\S]*event\.key !== ' '/);
assert.match(app, /function renderFarmMap\(s\)[\s\S]*s\.relays\?\./);
assert.doesNotMatch(app, /homeRelays|homeTempAgain|weatherSensorTemp|deviceRelays|homeMqttStatus|refreshBtn/);
assert.match(fs.readFileSync('dashboard/finance/index.html', 'utf8'), /index\.html#finance/);
assert.match(fs.readFileSync('dashboard/manifest.json', 'utf8'), /"theme_color":"#0B1220"/);
console.log('PASS dashboard pages: seven routes, map-first Home, accessible relay navigation, unique water controls, Finance deep link, Dark Tech tokens');
