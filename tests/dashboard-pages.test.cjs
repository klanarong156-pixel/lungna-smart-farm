const assert = require('node:assert/strict');
const fs = require('node:fs');
const html = fs.readFileSync('dashboard/index.html', 'utf8');
const css = fs.readFileSync('dashboard/css/app.css', 'utf8') + fs.readFileSync('dashboard/css/reference-layout.css', 'utf8');
const app = fs.readFileSync('dashboard/js/app.js', 'utf8');
const config = fs.readFileSync('dashboard/js/config.js', 'utf8');
const pageIds = [...html.matchAll(/data-page="([^"]+)"/g)].map(m => m[1]);
const navTargets = [...html.matchAll(/data-nav="([^"]+)"/g)].map(m => m[1]);
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(m => m[1]);
assert.deepEqual(pageIds, ['home','water','devices','system','weather','records']);
assert.deepEqual([...new Set(navTargets)], ['home','water','devices','weather','records','system']);
assert.ok(navTargets.every(target => pageIds.includes(target)), 'every navigation target has a page');
assert.equal(new Set(ids).size, ids.length, 'DOM IDs must be unique');
assert.match(html, /<header class="topbar">[\s\S]*?id="connection"/);
assert.doesNotMatch(html, /id="headerEsp"/);
assert.match(html, /<footer class="site-footer">/);
assert.match(html, /class="sidebar"[\s\S]*data-nav="records"/);
assert.match(html, /class="bottom-nav"[\s\S]*data-nav="records"/);
for (const token of ['--primary:','--primary-dark:','--primary-light:','--background:','--surface:','--surface-soft:','--text:','--text-muted:','--border:','--success:','--warning:','--danger:','--info:']) assert.ok(css.includes(token), `missing design token ${token}`);
assert.match(html, /DHT11/);
assert.doesNotMatch(html, /Soil Sensor|data-nav="settings"|data-nav="connection-page"|data-nav="events"/);
assert.match(html, /lungna-shell-v10/);
assert.match(html, /logo-suanlungna-modern\.png/);
assert.match(html, /farm-aerial\.webp[\s\S]*data-farm-zone="pump"[\s\S]*data-farm-zone="zone1"[\s\S]*data-farm-zone="lighthome"[\s\S]*data-farm-zone="lightsala"/);
assert.match(html, /ตำแหน่งอุปกรณ์เป็นสัดส่วนโดยประมาณ/);
assert.match(html, /ไม่แสดงพิกัดหรือขนาดพื้นที่จริง/);
const homeStart = html.indexOf('data-page="home"');
const waterStart = html.indexOf('data-page="water"');
const homeMarkup = html.slice(homeStart, waterStart);
assert.doesNotMatch(homeMarkup, /data-relay-toggle|data-mode|scheduleForm/, 'Home navigation must not issue commands');
assert.match(homeMarkup, /id="temperature"[\s\S]*id="humidity"[\s\S]*id="homeEsp"/);
assert.equal((homeMarkup.match(/data-home-relay=/g) || []).length, 4, 'Home shows the four actual relay controls as status shortcuts');
assert.match(html, /class="water-workspace"[\s\S]*id="waterRelays"[\s\S]*id="scheduleEditor"/);
assert.match(html, /id="page-system"[\s\S]*class="system-step"[\s\S]*id="mqttAutoStatus"[\s\S]*id="connectBtn"[\s\S]*id="systemCheck"[\s\S]*id="reloadDashboard"/);
assert.doesNotMatch(html, /adminInfo|showAdminInfo|connectionTimeline/);
assert.match(html, /class="weather-layout"[\s\S]*Open-Meteo/);
const weatherStart = html.indexOf('data-page="weather"');
const recordsStart = html.indexOf('data-page="records"');
const weatherMarkup = html.slice(weatherStart, recordsStart);
assert.equal((weatherMarkup.match(/<aside\b/g) || []).length, (weatherMarkup.match(/<\/aside>/g) || []).length);
assert.doesNotMatch(weatherMarkup, /GPS|UTM|\d{1,3}\.\d{4,}/, 'weather view must not expose precise location');
assert.match(weatherMarkup, /พยากรณ์ภูมิภาค/);
assert.match(html, /id="recordsEventsTab"[\s\S]*data-records-view="events"[\s\S]*id="recordsFinanceTab"[\s\S]*data-records-view="finance"/);
assert.match(html, /id="monthIncome"[\s\S]*id="monthExpense"[\s\S]*id="monthNet"[\s\S]*id="exportFinance"/);
assert.match(html, /id="financeDisclosure"[\s\S]*data-export-finance[\s\S]*id="financeForm"[\s\S]*id="clearLocal"/);
assert.match(html, /session นี้[\s\S]*localStorage/);
for (const duplicateId of ['homeRelays','homeTempAgain','homeHumidityAgain','homeHeartbeat','homeMqttStatus','weatherSensorTemp','weatherSensorHumidity','deviceRelays','refreshBtn']) assert.doesNotMatch(html, new RegExp(`id="${duplicateId}"`), `duplicate surface ${duplicateId} should be removed`);
assert.match(css, /prefers-reduced-motion: reduce/);
assert.match(css, /\.water-control-column \.relay-list\s*\{[^}]*grid-template-columns:\s*minmax\(0,\s*1fr\)/);
assert.match(css, /\.device-grid \.device-card\.controller-card\s*\{[^}]*grid-column:\s*1/);
assert.match(app, /connection-page': 'system'[\s\S]*settings: 'system'[\s\S]*events: 'records'[\s\S]*finance: 'records'/);
assert.match(app, /function setRecordsView\(view\)[\s\S]*recordsFinancePanel'[\s\S]*openFinance\) setRecordsView\('finance'\)/);
assert.match(app, /function openFarmZone\(relayId\)[\s\S]*?scheduleRelay'\)\.value = relayId[\s\S]*?navigate\('water'\)/);
assert.match(app, /event\.key !== 'Enter'[\s\S]*event\.key !== ' '/);
assert.match(app, /function renderFarmMap\(s\)[\s\S]*s\.relays\?\./);
assert.match(app, /function renderHomeEquipment\(s\)[\s\S]*data-home-relay-status/);
assert.match(app, /function exportFinanceCsv\(\)[\s\S]*data-export-finance/);
assert.doesNotMatch(app, /showAdminInfo|connectionTimeline|homeRelays|weatherSensorTemp|deviceRelays|homeMqttStatus|refreshBtn|headerEsp|homeLiveMark|systemConnection|homeRelaySummary|modeValue/);
const weatherConfig = /weather:\s*\{([^}]+)\}/.exec(config)?.[1] || '';
assert.ok(weatherConfig, 'weather config exists');
assert.doesNotMatch(weatherConfig, /\d{1,3}\.\d{3,}/, 'weather reference must be coarse, not a precise position');
const appIds = [...app.matchAll(/\$\('([^']+)'\)/g)].map(m => m[1]);
for (const id of new Set(appIds)) assert.ok(ids.includes(id), `app references missing DOM id ${id}`);
assert.match(fs.readFileSync('dashboard/finance/index.html', 'utf8'), /index\.html#finance/);
assert.match(fs.readFileSync('dashboard/manifest.json', 'utf8'), /"theme_color":"#F4F1E8"/);
console.log('PASS dashboard pages: reference-led six-route layout, safe controls, monthly finance, regional weather privacy, and unique DOM hooks');
