const assert = require('node:assert/strict');
const fs = require('node:fs');

const source = fs.readFileSync('firmware/esp8266/src/main.ino', 'utf8');

assert.match(source, /#define SMARTFARM_VERSION "V7\.2\.0-OTA-STABLE"/);
assert.match(source, /#define ENABLE_HTTP_OTA 0/);
assert.match(source, /char setupApPassword\[33\]/);
assert.match(source, /ESP\.random\(\)/);
assert.match(source, /SETUP_AP_PASSWORD_FILE\[\] = "\/setup_ap_password\.txt"/);
assert.match(source, /bool loadOrCreateSetupApPassword\(\)/);
assert.match(source, /LittleFS\.open\(SETUP_AP_PASSWORD_FILE, "r"\)/);
assert.match(source, /LittleFS\.open\(SETUP_AP_PASSWORD_FILE, "w"\)/);
assert.match(source, /loadOrCreateSetupApPassword\(\)/);
assert.match(source, /autoConnect\(WIFI_SETUP_AP_SSID,\s*setupApPassword\)/);
assert.match(source, /startConfigPortal\(WIFI_SETUP_AP_SSID,\s*setupApPassword\)/);
assert.match(source, /setAPCallback\(/);
assert.match(source, /Setup AP WPA2 password \(USB Serial only\): %s\\n/);
assert.match(source, /MQTT_BASE "\/admin\/setup-ap-password\/%06X\/request"/);
assert.match(source, /MQTT_BASE "\/admin\/setup-ap-password\/%06X\/response"/);
assert.match(source, /mqtt\.subscribe\(setupApPasswordRequestTopic\)/);
assert.doesNotMatch(source, /admin\/setup-ap-password\/\+\/request/);
assert.match(source, /d\["chip_id"\] = chipId/);
assert.match(source, /msg != "SHOW"/);
assert.match(source, /mqtt\.publish\(setupApPasswordResponseTopic,\s*setupApPassword,\s*false\)/);
assert.match(source, /type='password' autocomplete='new-password'/);
assert.match(source, /pPass\.setValue\("",\s*sizeof\(mqttPass\)\)/);
assert.match(source, /pOta\.setValue\("",\s*sizeof\(otaPass\)\)/);
assert.match(source, /pTelegramToken\.setValue\("",\s*sizeof\(telegramBotToken\)\)/);
assert.match(source, /updateSecretIfProvided\(mqttPass/);
assert.match(source, /updateSecretIfProvided\(otaPass/);
assert.match(source, /updateSecretIfProvided\(telegramBotToken/);
assert.doesNotMatch(source, /d\["setupApPass"\]/, 'keep setup AP PSK in its dedicated LittleFS file');
assert.doesNotMatch(source, /telegramTls\.setInsecure\(\)/);
assert.match(source, /telegramTls\.setTrustAnchors\(mqttTrustAnchor\)/);
assert.match(source, /telegramTls\.setX509Time\(\(time_t\)epoch\)/);
assert.match(source, /mqttTrustAnchor->getCount\(\)/);
assert.match(source, /emergency\/status/);
assert.match(source, /system\/error/);
assert.match(source, /otaFailureLock/);
assert.match(source, /digitalWrite\(relayPins\[i\], RELAY_OFF\)/);

console.log('PASS firmware source contract: validated TLS, OTA defaults, safety locks and diagnostics');
